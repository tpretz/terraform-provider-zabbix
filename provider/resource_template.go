// terraform resource create handler
func resourceTemplateCreate(d *schema.ResourceData, m interface{}) error {
	api := m.(*zabbix.API)

	item, err := buildTemplateObject(d, m)
	if err != nil {
		return err
	}
	items := []zabbix.Template{*item}

	err = api.TemplatesCreate(items)

	if err != nil {
		return err
	}

	log.Trace("crated template: %+v", items[0])

	d.SetId(items[0].TemplateID)

	return resourceTemplateRead(d, m)
}

// templateGroupSelectParam names the template.get parameter that returns group
// membership. Zabbix 7.2 removed "selectGroups" (deprecated since 6.2) in
// favour of "selectTemplateGroups"; on 7.2+ the old name is silently ignored,
// so the template reads back with no groups rather than erroring.
func templateGroupSelectParam(m interface{}) string {
	if m.(*zabbix.API).Config.Version >= zabbix.V72 {
		return "selectTemplateGroups"
	}
	return "selectGroups"
}

// terraform template read handler (data source)
func dataTemplateRead(d *schema.ResourceData, m interface{}) error {

	params := zabbix.Params{
		"filter":                    map[string]interface{}{},
		"selectMacros":              "extend",
		"selectParentTemplates":     "extend",
		templateGroupSelectParam(m): "extend",
	}

	if v := d.Get("host").(string); v != "" {
		params["filter"].(map[string]interface{})["host"] = v
	}

	if v := d.Get("name").(string); v != "" {
		params["filter"].(map[string]interface{})["name"] = v
	}

	if len(params["filter"].(map[string]interface{})) < 1 {
		return errors.New("no filter parameters provided")
	}
	log.Debug("Lookup of template with: %#v", params)

	if err := templateRead(d, m, params); err != nil {
		return err
	}
	return dataSourceFound(d, "template", "host", "name")
}

// terraform template read handler (resource)
func resourceTemplateRead(d *schema.ResourceData, m interface{}) error {
	log.Debug("Lookup of template with id %s", d.Id())

	return templateRead(d, m, zabbix.Params{
		"templateids":               d.Id(),
		"selectMacros":              "extend",
		"selectParentTemplates":     "extend",
		templateGroupSelectParam(m): "extend",
	})
}

// generic template read function
func templateRead(d *schema.ResourceData, m interface{}, params zabbix.Params) error {
	api := m.(*zabbix.API)

	templates, err := api.TemplatesGet(params)

	if err != nil {
		return err
	}

	if len(templates) < 1 {
		d.SetId("")
		return nil
	}
	if len(templates) > 1 {
		return errors.New("multiple templates found")
	}
	t := templates[0]

	log.Debug("Got template: %+v", t)

	d.Set("description", t.Description)
	d.Set("host", t.Host)
	d.Set("name", t.Name)
	d.Set("macro", flattenMacros(t.UserMacros))
	d.Set("groups", flattenHostGroupIds(t.Groups))
	d.Set("templates", flattenTemplateIds(t.ParentTemplates))
	d.Set("uuid", t.UUID)

	// The version-gated attributes come back as nil from a server that does
	// not have them. They are still written to state, as their zero value:
	// buildTemplateObject refuses to accept a non-zero value on such a
	// server, so the zero value is the only thing a configuration can hold,
	// and writing it keeps a freshly imported resource identical to a
	// freshly applied one.
	d.Set("vendor_name", derefOr(t.VendorName, ""))
	d.Set("vendor_version", derefOr(t.VendorVersion, ""))
	d.Set("readme", derefOr(t.Readme, ""))
	d.Set("wizard_ready", derefOr(t.WizardReady, "0") == "1")

	d.SetId(t.TemplateID)

	return nil
}

// build a template object from terraform data
//
// The vendor and wizard attributes only exist from a given server version on,
// and Zabbix 7.2 turned an unknown request property into a hard error, so each
// is written only when the server has it. Configuring one below its version is
// an error here rather than a silently ignored setting.
func buildTemplateObject(d *schema.ResourceData, m interface{}) (*zabbix.Template, error) {
	api := m.(*zabbix.API)

	item := zabbix.Template{
		Description:     d.Get("description").(string),
		Name:            d.Get("name").(string),
		Host:            d.Get("host").(string),
		Groups:          buildHostGroupIds(d.Get("groups").(*schema.Set)),
		LinkedTemplates: buildTemplateIds(d.Get("templates").(*schema.Set)),
	}

	vendorName := d.Get("vendor_name").(string)
	vendorVersion := d.Get("vendor_version").(string)
	if api.Config.Version >= zabbix.V64 {
		item.VendorName = &vendorName
		item.VendorVersion = &vendorVersion
	} else if vendorName != "" || vendorVersion != "" {
		return nil, errors.New("vendor_name and vendor_version require Zabbix 6.4 or later")
	}

	readme := d.Get("readme").(string)
	wizardReady := "0"
	if d.Get("wizard_ready").(bool) {
		wizardReady = "1"
	}
	if api.Config.Version >= zabbix.V74 {
		item.Readme = &readme
		item.WizardReady = &wizardReady
	} else if readme != "" || wizardReady == "1" {
		return nil, errors.New("readme and wizard_ready require Zabbix 7.4 or later")
	}

	item.UserMacros = macroGenerate(d)
	return &item, nil
}

// terraform update resource handler
func resourceTemplateUpdate(d *schema.ResourceData, m interface{}) error {
	api := m.(*zabbix.API)

	item, err := buildTemplateObject(d, m)
	if err != nil {
		return err
	}
	item.TemplateID = d.Id()

	// templates may need a bit extra effort
	if d.HasChange("templates") {
		old, new := d.GetChange("templates")
		diff := old.(*schema.Set).Difference(new.(*schema.Set))

		// removals, we need to unlink and clear.
		//
		// Filtered through existingTemplateIds for the same reason
		// resourceHostUpdate does it: Terraform will happily destroy a
		// zabbix_template in the same apply that unlinks it, and from Zabbix
		// 7.0 an unknown object id in templates_clear is a hard error rather
		// than a no-op. Deleting a template unlinks it anyway, so dropping the
		// dead ids loses nothing.
		if diff.Len() > 0 {
			toClear, err := existingTemplateIds(api, diff)
			if err != nil {
				return err
			}
			if len(toClear) > 0 {
				item.TemplatesClear = toClear
			}
		}
	}

	items := []zabbix.Template{*item}

	if err := api.TemplatesUpdate(items); err != nil {
		return err
	}

	return resourceTemplateRead(d, m)
}

// terraform delete handler
func resourceTemplateDelete(d *schema.ResourceData, m interface{}) error {
	api := m.(*zabbix.API)
	return api.TemplatesDeleteByIds([]string{d.Id()})
}
