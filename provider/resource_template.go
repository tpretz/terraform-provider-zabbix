// templateGroupsDescription documents the one field whose meaning depends on
// the server version: on 6.2+ a template belongs to template groups, below
// that to host groups. The id spaces are disjoint on 6.2+.
const templateGroupsDescription = "Group IDs this template belongs to. " +
	"On Zabbix 6.2 and later these are template group ids (zabbix_templategroup); " +
	"on 6.0/6.1 they are host group ids (zabbix_hostgroup)."

// Descriptions of the version-gated attributes. Each field simply does not
// exist on an older server -- from Zabbix 7.2 an unknown request property is a
// hard error rather than being ignored -- so the provider refuses the
// configuration rather than silently dropping it.
const (
	templateVendorNameDescription = "Template vendor name. Requires Zabbix 6.4 or later, " +
		"and must be set together with vendor_version."
	templateVendorVersionDescription = "Template vendor version. Requires Zabbix 6.4 or later, " +
		"and must be set together with vendor_name."
	templateReadmeDescription = "Template readme text, shown by the template wizard. " +
		"Requires Zabbix 7.4 or later."
	templateWizardReadyDescription = "Whether the template is ready to be offered by the " +
		"template wizard. Requires Zabbix 7.4 or later."
)

// template resource function
func resourceTemplate() *schema.Resource {
	return &schema.Resource{
		Description: "Manages a Zabbix template: a reusable collection of items, triggers, graphs and discovery rules that can be linked to many hosts.",
		Create:      resourceTemplateCreate,
		Read:        resourceTemplateRead,
		Update:      resourceTemplateUpdate,
		Delete:      resourceTemplateDelete,
		Importer: &schema.ResourceImporter{
			State: schema.ImportStatePassthrough,
		},

		// v0 -> v1: "groups" holds template group ids on Zabbix 6.2+ where it
		// previously held host group ids. See resourceTemplateStateUpgradeV0.
		SchemaVersion: 1,
		StateUpgraders: []schema.StateUpgrader{
			{
				Version: 0,
				Type:    resourceTemplateV0().CoreConfigSchema().ImpliedType(),
				Upgrade: resourceTemplateStateUpgradeV0,
			},
		},

		Schema: map[string]*schema.Schema{
			"groups": &schema.Schema{
				Type: schema.TypeSet,
				Elem: &schema.Schema{
					Type:         schema.TypeString,
					ValidateFunc: validation.StringMatch(regexp.MustCompile("^[0-9]+$"), "must be a numeric string"),
				},
				Required:    true,
				Description: templateGroupsDescription,
			},
			"host": &schema.Schema{
				Type:         schema.TypeString,
				Required:     true,
				Description:  "Technical template name, unique across the Zabbix server",
				ValidateFunc: validation.StringIsNotWhiteSpace,
			},
			"description": &schema.Schema{
				Type:        schema.TypeString,
				Optional:    true,
				Description: "Template description",
			},
			"name": &schema.Schema{
				Type:        schema.TypeString,
				Optional:    true,
				Computed:    true,
				Description: "Template display name. Defaults to the value of `host`",
			},
			"templates": &schema.Schema{
				Type:     schema.TypeSet,
				Optional: true,
				Elem: &schema.Schema{
					Type:         schema.TypeString,
					ValidateFunc: validation.StringMatch(regexp.MustCompile("^[0-9]+$"), "must be a numeric string"),
				},
				Description: "IDs of templates linked into this one, so their items and triggers are inherited",
			},
			"macro": macroSetSchema,
			"uuid": &schema.Schema{
				Type:        schema.TypeString,
				Computed:    true,
				Description: "Template UUID, generated by Zabbix",
			},
			"vendor_name": &schema.Schema{
				Type:         schema.TypeString,
				Optional:     true,
				Description:  templateVendorNameDescription,
				RequiredWith: []string{"vendor_version"},
			},
			"vendor_version": &schema.Schema{
				Type:         schema.TypeString,
				Optional:     true,
				Description:  templateVendorVersionDescription,
				RequiredWith: []string{"vendor_name"},
			},
			"readme": &schema.Schema{
				Type:        schema.TypeString,
				Optional:    true,
				Description: templateReadmeDescription,
			},
			"wizard_ready": &schema.Schema{
				Type:        schema.TypeBool,
				Optional:    true,
				Default:     false,
				Description: templateWizardReadyDescription,
			},
		},
	}
}

